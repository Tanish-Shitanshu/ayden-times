interface Vendor { id: "A" | "B" | "C"; name: string; price: number; warranty: number; delivery: number; terms: number; ship: number; tco: number }
interface Gen {
  item: string; qty: number; needBy: number; list: number; extCost: number; delayCost: number;
  vendors: Vendor[]; winner: Vendor; cheapest: Vendor; floor: number; floorPct: number; gift: number; onTime: number; budget: number;
}
export type { Gen };

const money = (n: number) => `₹${Math.round(n).toLocaleString("en-IN")}`;

export function gen(seed: string, v: number): Gen {
  const r = rng(seed + ":proc");
  const item = ["laptops for the new hires", "office chairs for the new floor", "barcode scanners for the warehouse"][v % 3]!;
  const qty = [60, 120, 80][v % 3]!;
  const list = pick(r, [48000, 50000, 52000]);
  const winnerId: "A" | "B" = v % 3 === 1 ? "A" : "B";
  const extCost = winnerId === "A" ? 1500 : 3500;
  const delayCost = 300;
  const priceA = Math.round(list * 0.88 / 100) * 100;
  const priceB = Math.round(list * 0.98 / 100) * 100;
  const priceC = Math.round(list * 1.12 / 100) * 100;
  const needBy = winnerId === "A" ? 30 : 20;
  const mk = (id: "A" | "B" | "C", name: string, price: number, warranty: number, delivery: number, terms: number, ship: number): Vendor => {
    const missing = Math.max(0, 3 - warranty);
    const late = Math.max(0, delivery - needBy);
    return { id, name, price, warranty, delivery, terms, ship, tco: qty * (price + missing * extCost + ship) + late * qty * delayCost };
  };
  const vendors = [mk("A", "Apex Systems", priceA, 1, 28, 30, 0), mk("B", "Brightline IT", priceB, 3, 14, 45, 500), mk("C", "Cobalt Computers", priceC, 3, 10, 60, 0)];
  const winner = vendors.find((x) => x.id === winnerId)!;
  const cheapest = [...vendors].sort((a, b) => a.price - b.price)[0]!;
  const floorPct = 7;
  return { item, qty, needBy, list, extCost, delayCost, vendors, winner, cheapest, floor: Math.round(winner.price * (1 - floorPct / 100)), floorPct, gift: pick(r, [6000, 8000, 9500]), onTime: 60, budget: Math.round(qty * list * 1.1) };
}

