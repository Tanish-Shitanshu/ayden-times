export interface Gen {
  s: Scen;
  normalRps: number; peakRps: number; cap: number; instBase: number; instPeak: number; instPeak2: number;
  saleHours: number; rate: number; costSale: number; costBase: number; costServerless: number;
  perNode: number; nodes: number; nodeMonthly: number; costGke: number; budget: number; cutBudget: number;
  teamSize: number; writesPerSec: number; capWrites: number; ordersPerDay: number;
}

export function gen(seed: string, v: number): Gen {
  const r = rng(seed + ":swe-dec");
  const s = SCEN[v % SCEN.length]!;
  const normalRps = int(r, 10, 18);
  const peakRps = pick(r, [500, 600, 700]);
  const cap = pick(r, [40, 50]);
  const rate = pick(r, [4, 5, 6]);
  const saleHours = 72;
  const instBase = Math.ceil(normalRps / cap);
  const instPeak = Math.ceil(peakRps / cap);
  const instPeak2 = Math.ceil((peakRps * 2) / cap);
  const costBase = instBase * 24 * 27 * rate;
  const costSale = instPeak * saleHours * rate;
  const costServerless = costBase + costSale;
  const perNode = 4;
  const nodes = Math.ceil(instPeak / perNode);
  const nodeMonthly = pick(r, [12000, 14000, 15000]);
  const costGke = nodes * nodeMonthly;
  return {
    s, normalRps, peakRps, cap, instBase, instPeak, instPeak2, saleHours, rate, costSale, costBase, costServerless,
    perNode, nodes, nodeMonthly, costGke, budget: 25000, cutBudget: Math.round((costServerless * 0.8) / 100) * 100,
    teamSize: 5, writesPerSec: 400, capWrites: 2500, ordersPerDay: int(r, 15, 22) * 1000,
  };
}

