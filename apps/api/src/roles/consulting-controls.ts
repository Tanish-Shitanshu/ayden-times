type ExType = "po" | "limit" | "dup" | "self";
interface Row { ref: string; inv: string; vendor: string; amount: number; po: "Y" | "N"; requester: string; approver: string; ex?: ExType }
export interface Gen { rows: Row[]; exceptions: { ref: string; type: ExType; amount: number; rating: "High" | "Medium" | "Low" }[]; total: number; n: number; high: number }

const r2 = (n: number) => Math.round(n * 100) / 100;
const VENDORS = ["Kaveri Packaging", "Orbit Logistics", "Shreeji Stationers", "BlueLine IT", "Nirmal Chemicals", "Metro Facility Services"];
const PEOPLE = ["Sanjay", "Pooja", "Imtiaz", "Neha", "Rahul", "Divya", "Karthik", "Smita"];

export function gen(seed: string, v: number): Gen {
  const r = rng(seed + ":ctl");
  const n = 30;
  const rows: Row[] = [];
  for (let i = 0; i < n; i++) {
    const amount = r2(0.3 + r() * 0.65 + (r() < 0.35 ? 1.3 + r() * 2.2 : 0));
    const requester = pick(r, PEOPLE);
    let approver = amount > 1 ? "Meera Pillai (Finance Head)" : "Dept Manager";
    rows.push({ ref: `P-${String(i + 1).padStart(2, "0")}`, inv: `INV-${int(r, 7000, 7999)}`, vendor: pick(r, VENDORS), amount, po: "Y", requester, approver });
  }
  // pick distinct rows for the injected exceptions
  const idx = [...Array(n).keys()].sort(() => r() - 0.5);
  const take = () => idx.pop()!;
  const counts = { po: 2 + (v % 2), limit: 2, dup: 1, self: 1 + (v === 2 ? 1 : 0) };
  for (let k = 0; k < counts.po; k++) { const x = rows[take()]!; x.po = "N"; x.ex = "po"; }
  for (let k = 0; k < counts.limit; k++) { const x = rows[take()]!; x.amount = r2(1.2 + r() * 2.6); x.approver = "Dept Manager"; x.ex = "limit"; }
  for (let k = 0; k < counts.self; k++) { const x = rows[take()]!; x.approver = x.requester; x.ex = "self"; if (x.amount > 1) x.amount = r2(0.4 + r() * 0.5); }
  {
    const x = rows[take()]!;
    const orig = rows.find((y) => !y.ex && y !== x && y.amount <= 1)!;
    x.inv = orig.inv; x.vendor = orig.vendor; x.amount = orig.amount; x.approver = "Dept Manager"; x.ex = "dup";
  }
  const rate = (t: ExType, amt: number): "High" | "Medium" | "Low" => (t === "dup" || t === "self" || amt > 2 ? "High" : "Medium");
  const exceptions = rows.filter((x) => x.ex).map((x) => ({ ref: x.ref, type: x.ex!, amount: x.amount, rating: rate(x.ex!, x.amount) }));
  return { rows, exceptions, total: r2(exceptions.reduce((s, e) => s + e.amount, 0)), n, high: exceptions.filter((e) => e.rating === "High").length };
}

const TYPE_RE: Record<ExType, RegExp> = {
  po: /(\bpo\b|purchase order|no po|missing po)/i,
  limit: /(limit|above|exceed|authori[sz]|finance head|approval)/i,
  dup: /(duplicate|twice|double|same invoice|paid again)/i,
  self: /(self|same person|requester|segregation|approved (his|her|their) own|own payment)/i,
};
const aSeq = (c: { session: { artifacts: Record<string, { seq?: number } | undefined> } }, id: string) => c.session.artifacts[id]?.seq;
const AGREE = /(^|\b)(ok(ay)?|sure|fine|agreed?|will do|sounds good|yes|deal|no problem|i can|i'?ll (send|do|change)|let'?s do that)\b/i;
const REFUSE = /(cannot|can'?t|can not|not able|won'?t|will not|\bno\b|not allowed|policy|independen|confidential|unless|evidence|rule|manager|ananya|speak to|check with)/i;

function exRows(c: { artifacts: Record<string, string> }, g: Gen) {
  const rows = parseSheet(c.artifacts["ar_exceptions"] ?? "");
  const by = (ref: string) => rows.find((r) => new RegExp(`\\b${ref}\\b`, "i").test(r.text));
  const listed = new Set(rows.flatMap((r) => [...r.text.matchAll(/\bP-\d{2}\b/gi)].map((m) => m[0]!.toUpperCase())));
  return { rows, by, listed };
}

